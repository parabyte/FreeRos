    XTIDE_EDD_ENABLED="n"
    XTIDE_COMPATIBLE_TABLES="n"
    XTIDE_BOOT_MENU_ENABLED="n"
    XTIDE_HOTKEYS_ENABLED="n"
    XTIDE_POWER_MANAGEMENT_ENABLED="n"
    XTIDE_VERY_LATE_INIT="n"
elif [ "$XTIDE_EMBEDDED_IN_ROS" = "y" ]; then
    XTIDE_EDD_ENABLED="n"
    XTIDE_COMPATIBLE_TABLES="n"
    XTIDE_BOOT_MENU_ENABLED="n"
    XTIDE_HOTKEYS_ENABLED="n"
    XTIDE_POWER_MANAGEMENT_ENABLED="n"
    XTIDE_VERY_LATE_INIT="n"
