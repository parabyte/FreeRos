XTIDE_MASTER_CYLINDERS="${CONFIG_XTIDE_MASTER_CYLINDERS:-1024}"
XTIDE_MASTER_HEADS="${CONFIG_XTIDE_MASTER_HEADS:-16}"
XTIDE_MASTER_SECTORS="${CONFIG_XTIDE_MASTER_SECTORS:-63}"
