    # Hardware
    emit "BIOS_CFG_BASE_MEMORY_KB" "${BASE_MEMORY_KB}"
    emit "BIOS_CFG_HAS_PARADISE_PEGA1A" "$(bool_val "$HAS_PARADISE_PEGA1A")"
