#!/bin/bash
#
# Generate build/config_autogen.h and build/config.mk from .config
#
# This translates Kconfig-style CONFIG_* names into the BIOS_CFG_*
# names expected by the BIOS source code.
#

set -e

CONFIG="${1:-.config}"
HEADER="${2:-build/config_autogen.h}"
MAKEFILE="${3:-build/config.mk}"

if [ ! -f "$CONFIG" ]; then
    echo "mkconfig.sh: $CONFIG not found" >&2
    exit 1
fi

mkdir -p "$(dirname "$HEADER")" "$(dirname "$MAKEFILE")"

. "$CONFIG"

# Kconfig writes '# CONFIG_FOO is not set' for disabled booleans.
# Bash sourcing treats them as comments, leaving the variable unset, which
# causes ${CONFIG_FOO:-y} defaults to silently re-enable the option.
# Explicitly set every "not set" variable to "n" so disabled booleans stay
# disabled while genuinely missing legacy keys can still fall back.
while IFS= read -r line; do
    case "$line" in
        '# CONFIG_'*' is not set')
            varname="${line#\# }"
            varname="${varname%% *}"
            eval "$varname=n"
            ;;
    esac
done < "$CONFIG"

# --- Helper: emit a #define ---
emit() {
    echo "#undef  $1"
    echo "#define $1 $2"
}

emit_str() {
    echo "#undef  $1"
    echo "#define $1 \"$2\""
}

bool_val() {
    if [ "$1" = "y" ]; then echo 1; else echo 0; fi
}

# Strip 0x prefix if present (Kconfig hex values include it)
strip_0x() {
    echo "${1#0x}"
}

# --- Floppy drive type mapping ---
floppy_type_macro() {
    case "$1" in
        180K) echo "BIOS_FLOPPY_TYPE_180K_525SD" ;;
        360K) echo "BIOS_FLOPPY_TYPE_360K_525DD" ;;
        720K) echo "BIOS_FLOPPY_TYPE_720K_35DD" ;;
        *)    echo "BIOS_FLOPPY_TYPE_NONE" ;;
    esac
}

