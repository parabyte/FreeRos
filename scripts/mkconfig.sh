    emit "BIOS_CFG_OPTION_ROM_SCAN_ENABLED" "$(bool_val "$OPTION_ROM_SCAN_ENABLED")"
    emit "BIOS_CFG_VIDEO_OPTION_ROM_SCAN_START" "$VIDEO_OPTION_ROM_SCAN_START"
    emit "BIOS_CFG_VIDEO_OPTION_ROM_SCAN_END" "$VIDEO_OPTION_ROM_SCAN_END"
    emit "BIOS_CFG_VIDEO_OPTION_ROM_SCAN_STEP" "0x0080"
