    emit "BIOS_CFG_XTIDE_STEAL_SIZE" "${XTIDE_STEAL_SIZE}"
    emit "BIOS_CFG_XTIDE_EDD_ENABLED" "$(bool_val "$XTIDE_EDD_ENABLED")"
