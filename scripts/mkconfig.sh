    XTIDE_FULL_MODE="$CONFIG_XTIDE_FULL_MODE"
elif [ "$TARGET" = "pc1640dd" ]; then
    XTIDE_FULL_MODE="n"
else
    XTIDE_FULL_MODE="y"
fi
