    echo ""

    # Identity
    emit_str "BIOS_CFG_MACHINE_NAME" "${MACHINE_NAME}"
    emit_str "BIOS_CFG_BIOS_BRAND" "${CONFIG_BIOS_BRAND}"
    emit_str "BIOS_CFG_BIOS_STYLE_NAME" "${BIOS_STYLE_NAME}"
