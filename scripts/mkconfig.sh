    emit "BIOS_CFG_HAS_BATTERY_BACKED_RTC" "$(bool_val "$HAS_BATTERY_BACKED_RTC")"
    emit "BIOS_CFG_HAS_MATH_COPROCESSOR" "$(bool_val "$CONFIG_HAS_MATH_COPROCESSOR")"
    emit "BIOS_CFG_HAS_DMA_CONTROLLER" "$(bool_val "$HAS_DMA_CONTROLLER")"
    emit "BIOS_CFG_POST_ROS_CHECKSUM_TEST_ENABLED" "$(bool_val "$POST_ROS_CHECKSUM_TEST_ENABLED")"
    emit "BIOS_CFG_POST_VIDEO_MEMORY_TEST_ENABLED" "$(bool_val "$POST_VIDEO_MEMORY_TEST_ENABLED")"
